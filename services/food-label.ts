// 식약처 DB 라벨을 **화면에 보여줄 이름**으로 다듬는다. 조회 키는 절대 바꾸지 않는다 —
// 저장·estimate 재조회는 원본 `food_label` 그대로여야 한다.
//
// 식약처 라벨에는 언더스코어가 두 가지 뜻으로 섞여 있다(실측, 14,520/15,553행):
//
//   ① 카테고리_상품명   "샤베트_메론코코샤베트" · "과ㆍ채주스_토마토 주스" · "피자_게살크림피자"
//   ② 음식명_재료       "소고기국_무_당면" · "삼겹살구이_고추장" · "햄버거_소고기패티_토마토_양상추"
//
// **그래서 "언더스코어 뒤만 남기기"는 쓸 수 없다.** ②에 적용하면 "소고기국_무_당면"이 "당면"이
// 되어 아예 다른 음식이 된다. 접두사가 카테고리인지 아닌지를 이름만 보고 일반적으로 판정할
// 방법은 없다.
//
// 대신 **확실한 경우에만** 접두사를 뗀다 — 접두사(또는 그 끝 두 글자)가 뒤쪽에 다시 나타나면
// 같은 말이 두 번 적힌 것이므로 카테고리로 본다. 그 외에는 언더스코어만 공백으로 바꿔
// 정보를 그대로 둔다. 잘못 잘라 다른 음식으로 보이게 하는 것보다 조금 긴 이름이 낫다.
//
//   샤베트_메론코코샤베트      → 메론코코샤베트     ("샤베트"가 뒤에 다시 나온다)
//   과ㆍ채주스_토마토 주스     → 토마토 주스       (끝 두 글자 "주스"가 뒤에 있다)
//   홍차_홍차 아이스(ICED)   → 홍차 아이스(ICED)
//   소고기국_무_당면          → 소고기국 무 당면   (재료 표기 — 보존)
//   커피_민트 모카            → 커피 민트 모카     (판정 불가 — 보존)
export function formatFoodLabel(label: string): string {
  if (!label.includes('_')) {
    return label;
  }

  const [head, ...rest] = label.split('_');
  const tail = rest.join(' ');

  if (head.length >= 2 && (tail.includes(head) || tail.includes(head.slice(-2)))) {
    return tail;
  }

  return [head, ...rest].join(' ');
}
